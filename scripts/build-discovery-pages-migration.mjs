import {writeFile} from 'node:fs/promises';
import {DISCOVERY_SQL} from '../workers/api/src/discovery.js';
import {catalogFields} from '../site/js/atlas-catalog.js';
const quoted=values=>values.map(v=>"'"+v.replaceAll("'","''")+"'").join(',');
const select=DISCOVERY_SQL.replace('SELECT payload,md5(payload::text) AS revision FROM bundle','SELECT payload,md5(payload::text) AS revision FROM bundle');
const migration=`-- Generated by scripts/build-discovery-pages-migration.mjs. Derived delivery
-- snapshots only: no canonical records are changed. Apply with an administrative
-- role, then grant function execution to the existing API role explicitly.
BEGIN;
CREATE TABLE IF NOT EXISTS atlas.discovery_delivery_snapshots (
 revision text PRIMARY KEY CHECK(revision ~ '^[0-9a-f]{32}$'),
 characters bigint NOT NULL, pages integer NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS atlas.discovery_delivery_pages (
 revision text NOT NULL REFERENCES atlas.discovery_delivery_snapshots(revision) ON DELETE CASCADE,
 page integer NOT NULL, payload_piece text NOT NULL CHECK(length(payload_piece)<=65536),
 PRIMARY KEY(revision,page)
);
REVOKE ALL ON atlas.discovery_delivery_snapshots,atlas.discovery_delivery_pages FROM PUBLIC;
CREATE OR REPLACE FUNCTION atlas.discovery_public_sources(p_sources jsonb)
RETURNS jsonb LANGUAGE plpgsql IMMUTABLE SET search_path=pg_catalog AS $sources$
DECLARE v jsonb:=p_sources;result jsonb;
BEGIN
 IF jsonb_typeof(v)='string' THEN
  BEGIN v:=(v#>>'{}')::jsonb;EXCEPTION WHEN invalid_text_representation THEN RETURN '[]'::jsonb; END;
 END IF;
 IF jsonb_typeof(v) IS DISTINCT FROM 'array' THEN RETURN '[]'::jsonb; END IF;
 SELECT COALESCE(jsonb_agg(jsonb_build_object('url',x.url)||
  CASE WHEN x.quote<>'' THEN jsonb_build_object('quote',x.quote) ELSE '{}'::jsonb END ORDER BY x.ord),'[]'::jsonb)
 INTO result FROM (
  SELECT ord,btrim(regexp_replace(e->>'url','^\\s+|\\s+$','','g')) AS url,
   CASE WHEN jsonb_typeof(e->'quote')='string' THEN btrim(regexp_replace(e->>'quote','\\s+',' ','g')) ELSE '' END AS quote
  FROM jsonb_array_elements(v) WITH ORDINALITY items(e,ord) WHERE jsonb_typeof(e)='object'
 ) x WHERE x.url ~ '^https?://';
 RETURN result;
END $sources$;
REVOKE ALL ON FUNCTION atlas.discovery_public_sources(jsonb) FROM PUBLIC;
CREATE OR REPLACE FUNCTION atlas.refresh_discovery_delivery_snapshot()
RETURNS TABLE(revision text, characters bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,atlas,public AS $body$
DECLARE v_payload jsonb; v_catalog jsonb; v_revision text; v_public jsonb; v_text text; v_characters bigint; v_pages integer;
BEGIN
 -- One statement builds catalog, evidence, graph, media and revision together.
 SELECT b.payload,b.revision INTO v_payload,v_revision FROM (${select}) b;
 IF EXISTS(WITH ids AS MATERIALIZED (SELECT o->>'id' AS id FROM jsonb_array_elements(v_payload->'graph'->'objects') o)
  SELECT 1 FROM jsonb_array_elements(v_payload->'graph'->'relationships') r
  LEFT JOIN ids f ON f.id=r->>'from_id' LEFT JOIN ids t ON t.id=r->>'to_id'
  WHERE f.id IS NULL OR t.id IS NULL)
 THEN RAISE EXCEPTION 'Dangling graph relationship'; END IF;
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(v_payload->'catalog') c
  WHERE c->'document' IS NULL OR c->'document'->>'id' IS DISTINCT FROM c->>'id'
   OR c->'document'->>'type' IS DISTINCT FROM 'company'
   OR c->'document'->'published'='false'::jsonb OR c->>'id' LIKE 'funding-rule-%'
   OR c->>'visible' IS DISTINCT FROM 'true' OR c->>'review_current' IS DISTINCT FROM 'true'
   OR c->>'review_id' IS NULL OR c->>'decision' NOT IN ('retain','correct'))
 THEN RAISE EXCEPTION 'Invalid offering projection'; END IF;
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(v_payload->'catalog') c GROUP BY c->>'id' HAVING count(*)>1)
 THEN RAISE EXCEPTION 'Duplicate catalog identity'; END IF;
 -- An unchanged immutable revision needs no repeated sanitize/stringify/split.
 -- Require every indexed page before accepting an existing manifest.
 IF EXISTS(SELECT 1 FROM atlas.discovery_delivery_snapshots s WHERE s.revision=v_revision
  AND s.pages>0 AND (SELECT count(*) FROM atlas.discovery_delivery_pages p WHERE p.revision=s.revision)=s.pages
  AND (SELECT min(p.page) FROM atlas.discovery_delivery_pages p WHERE p.revision=s.revision)=0
  AND (SELECT max(p.page) FROM atlas.discovery_delivery_pages p WHERE p.revision=s.revision)=s.pages-1)
 THEN RETURN QUERY SELECT s.revision,s.characters FROM atlas.discovery_delivery_snapshots s WHERE s.revision=v_revision; RETURN; END IF;
 -- Mirror projectCatalog's allowlist before any catalog data reaches clients.
 v_catalog:=v_payload->'catalog';
 v_payload:=jsonb_set(v_payload,'{logos}',COALESCE((SELECT jsonb_agg(l ORDER BY l#>>'{}')
  FROM jsonb_array_elements(v_payload->'logos') l
  WHERE EXISTS(SELECT 1 FROM jsonb_array_elements(v_catalog) c WHERE c->>'id'=l#>>'{}')),'[]'::jsonb));
 v_payload:=jsonb_set(v_payload,'{funding}',COALESCE((SELECT jsonb_agg(jsonb_set(f,'{sources}',atlas.discovery_public_sources(f->'sources')) ORDER BY f->>'entry_id',f->>'funder_id')
  FROM jsonb_array_elements(v_payload->'funding') f),'[]'::jsonb));
 SELECT jsonb_set(v_payload,'{catalog}',COALESCE(jsonb_agg(
  jsonb_build_object('id',c->'id','visible',c->'visible','review_id',c->'review_id',
   'review_current',c->'review_current','decision',c->'decision','document',
   (SELECT COALESCE(jsonb_object_agg(d.key,
     CASE WHEN d.key='deep_dive' AND jsonb_typeof(d.value)='object' THEN
      (SELECT COALESCE(jsonb_object_agg(e.key,e.value),'{}'::jsonb) FROM jsonb_each(d.value) e
       WHERE e.key IN (${quoted(['product','buyer','payer','sources','risks','open_questions','note'])}))
     WHEN d.key='deep_dive' AND d.value NOT IN ('null'::jsonb,'false'::jsonb,'0'::jsonb,'""'::jsonb) THEN '{}'::jsonb
     WHEN d.key='related' THEN
      CASE WHEN jsonb_typeof(d.value)='array' THEN
       (SELECT COALESCE(jsonb_agg(r ORDER BY ord),'[]'::jsonb) FROM jsonb_array_elements(d.value) WITH ORDINALITY related(r,ord)
        WHERE jsonb_typeof(r)='string' AND EXISTS(SELECT 1 FROM jsonb_array_elements(v_catalog) a WHERE a->>'id'=r#>>'{}'))
      ELSE '[]'::jsonb END
     ELSE d.value END),'{}'::jsonb)
    FROM jsonb_each(c->'document') d WHERE d.key IN (${quoted(catalogFields)})))
  ORDER BY c->>'id'),'[]'::jsonb)) INTO v_public
 FROM jsonb_array_elements(v_payload->'catalog') c;
 v_text:=v_public::text;v_characters:=length(v_text);v_pages:=ceil(v_characters/65536.0)::integer;
 INSERT INTO atlas.discovery_delivery_snapshots(revision,characters,pages)
 VALUES(v_revision,v_characters,v_pages) ON CONFLICT DO NOTHING;
 INSERT INTO atlas.discovery_delivery_pages(revision,page,payload_piece)
 SELECT v_revision,n,substring(v_text FROM (n*65536+1) FOR 65536)
 FROM generate_series(0,v_pages-1) n ON CONFLICT DO NOTHING;
 -- Retain at most 20 immutable revisions; a racing reader retries on expiry.
 DELETE FROM atlas.discovery_delivery_snapshots s WHERE s.revision<>v_revision
  AND (s.created_at<now()-interval '2 days' OR s.revision NOT IN
   (SELECT x.revision FROM atlas.discovery_delivery_snapshots x ORDER BY (x.revision=v_revision) DESC,x.created_at DESC,x.revision LIMIT 20));
 RETURN QUERY SELECT v_revision,s.characters FROM atlas.discovery_delivery_snapshots s WHERE s.revision=v_revision;
END $body$;
CREATE OR REPLACE FUNCTION atlas.read_discovery_delivery_page(p_revision text,p_page integer)
RETURNS TABLE(revision text,page integer,pages integer,payload_piece text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,atlas,public AS $body$
 SELECT s.revision,p.page,s.pages,p.payload_piece
 FROM atlas.discovery_delivery_snapshots s JOIN atlas.discovery_delivery_pages p ON p.revision=s.revision
 WHERE s.revision=p_revision AND p.page=p_page AND p_revision ~ '^[0-9a-f]{32}$'
 AND p_page>=0

$body$;
REVOKE ALL ON FUNCTION atlas.refresh_discovery_delivery_snapshot() FROM PUBLIC;
REVOKE ALL ON FUNCTION atlas.read_discovery_delivery_page(text,integer) FROM PUBLIC;
COMMIT;
`;
await writeFile(new URL('./migrations/20261010-discovery-delivery-pages.sql',import.meta.url),migration);
